#!/usr/bin/env bash
# Supabase Auth settings for the Docker-free local stack, as GOTRUE_* environment variables.
# These MUST mirror the [auth] sections of supabase/config.toml (what `supabase start` and the
# hosted project use). scripts/local-auth/check-config.mjs fails CI if the two drift apart.
cat <<'EOF'
GOTRUE_DISABLE_SIGNUP=true
GOTRUE_EXTERNAL_EMAIL_ENABLED=true
GOTRUE_EXTERNAL_PHONE_ENABLED=false
GOTRUE_EXTERNAL_ANONYMOUS_USERS_ENABLED=false
GOTRUE_EXTERNAL_APPLE_ENABLED=false
GOTRUE_EXTERNAL_GOOGLE_ENABLED=false
GOTRUE_SECURITY_MANUAL_LINKING_ENABLED=false
GOTRUE_MAILER_AUTOCONFIRM=false
GOTRUE_MAILER_OTP_LENGTH=6
GOTRUE_MAILER_OTP_EXP=600
GOTRUE_PASSWORD_MIN_LENGTH=15
GOTRUE_SECURITY_REFRESH_TOKEN_ROTATION_ENABLED=true
GOTRUE_SECURITY_REFRESH_TOKEN_REUSE_INTERVAL=0
GOTRUE_SECURITY_UPDATE_PASSWORD_REQUIRE_REAUTHENTICATION=true
GOTRUE_RATE_LIMIT_EMAIL_SENT=1000
GOTRUE_RATE_LIMIT_TOKEN_REFRESH=1000
GOTRUE_RATE_LIMIT_VERIFY=1000
GOTRUE_RATE_LIMIT_OTP=1000
GOTRUE_HOOK_CUSTOM_ACCESS_TOKEN_ENABLED=true
GOTRUE_HOOK_CUSTOM_ACCESS_TOKEN_URI=pg-functions://postgres/public/auth_custom_access_token_hook
GOTRUE_HOOK_SEND_EMAIL_ENABLED=true
GOTRUE_HOOK_SEND_EMAIL_URI=pg-functions://postgres/public/auth_send_email_hook
GOTRUE_HOOK_BEFORE_USER_CREATED_ENABLED=true
GOTRUE_HOOK_BEFORE_USER_CREATED_URI=pg-functions://postgres/public/auth_before_user_created_hook
EOF
